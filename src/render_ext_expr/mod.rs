//! render_ext_expr — drop-in handler registry for ExtExpr nodes.
//!
//! Mirrors `render_ext` (for IrStmt::Ext) but for IrExpr::Ext.
//! Each handler file in `handlers/` renders one tag; build.rs scans
//! the directory and generates the tag → handler dispatch.
//!
//! A backend's `IrExpr::Ext` arm calls [`render_with`] (its own child
//! renderer wired in, so shared handlers can build target-language
//! expression trees); if no handler matches, it gets None and keeps its
//! own fallback (an `sh2.*` stub or a loud refusal — never a silent
//! wrong answer).

use crate::shir_nodes::ExtExpr;

/// Which backend is requesting rendering.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Backend {
    Perl,
    Estree,
    Go,
    Rust,
    C,
    Zig,
    Sh,
    Glsl,
    Python,
    Java,
}

/// The invoking backend's OWN child-expression renderer. A backend that
/// wants shared handlers to build target-language expression trees
/// implements this for its renderer and passes `&mut self`.
///
/// This is a TRAIT (not a closure) so a backend can hand out `&mut self`
/// without the handler also holding a `&mut` to it — the two-level borrow
/// a `FnMut` capturing `self` cannot express.
pub(crate) trait ChildExprRenderer {
    /// Render `e` as an expression in the backend's language. `None` when
    /// the backend cannot render that shape — the handler must then refuse
    /// (never emit a broken partial).
    fn render_child(&mut self, e: &crate::ir::IrExpr) -> Option<String>;
}

/// Render context for expression handlers.
///
/// `child` lives behind a `RefCell` so the handlers keep the historical
/// `&ExprRenderCtx` signature (dozens of call sites): a handler borrows it
/// mutably only for the call that renders a child expression.
pub(crate) struct ExprRenderCtx<'a> {
    pub backend: Backend,
    pub indent: usize,
    child: std::cell::RefCell<Option<&'a mut dyn ChildExprRenderer>>,
}

impl<'a> ExprRenderCtx<'a> {
    /// A context with no child renderer: a handler can build only from
    /// literals (the shape every pre-existing call site had).
    pub(crate) fn bare(backend: Backend, indent: usize) -> Self {
        ExprRenderCtx { backend, indent, child: std::cell::RefCell::new(None) }
    }

    /// A context wired to the invoking backend's own expression renderer.
    pub(crate) fn with_child(
        backend: Backend,
        indent: usize,
        child: &'a mut dyn ChildExprRenderer,
    ) -> Self {
        ExprRenderCtx { backend, indent, child: std::cell::RefCell::new(Some(child)) }
    }

    /// Render a child expression in the invoking backend's language.
    ///
    /// `None` when no child renderer was registered — the handler must then
    /// refuse instead of emitting a broken partial. The borrow is taken and
    /// released inside this call, so a child renderer that itself renders an
    /// Ext node (re-entering the dispatch) is safe.
    pub(crate) fn child(&self, e: &crate::ir::IrExpr) -> Option<String> {
        let mut b = self.child.borrow_mut();
        let f = b.as_mut()?;
        f.render_child(e)
    }
}

// The handler-leaf modules (mod list generated by build.rs).
pub(crate) mod handlers;

// The generated tag → handler dispatch (build.rs scans handlers/).
include!(concat!(env!("OUT_DIR"), "/render_ext_expr_gen.rs"));

/// Render an ExtExpr node with no child renderer (the registry's minimal
/// entry point; a handler needing children refuses).
pub(crate) fn render(n: &dyn ExtExpr, ctx: &ExprRenderCtx) -> Option<String> {
    render_ext_expr_dispatch(n, ctx)
}

/// Render an ExtExpr node with the invoking backend's child renderer wired
/// in, so shared handlers can recurse into the backend's OWN expression
/// emitter. This is the entry point a backend should call.
pub(crate) fn render_with(
    n: &dyn ExtExpr,
    backend: Backend,
    indent: usize,
    child: &mut dyn ChildExprRenderer,
) -> Option<String> {
    let ctx = ExprRenderCtx::with_child(backend, indent, child);
    render_ext_expr_dispatch(n, &ctx)
}
